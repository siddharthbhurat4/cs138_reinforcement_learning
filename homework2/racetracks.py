def make_grid(layout):
    """Layout strings (top row first) -> int array indexed grid[y, x], y = 0 at the bottom."""
    if len({len(row) for row in layout}) != 1:
        raise ValueError("all rows of a layout must have the same length")
    grid = np.array([[int(ch) for ch in row] for row in layout], dtype=int)
    return grid[::-1]          # flip so the bottom row of the drawing becomes y = 0